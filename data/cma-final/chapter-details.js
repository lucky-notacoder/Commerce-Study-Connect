// Align chapter keys with chapters.js (same order) so every listed chapter shows its notes.
(() => {
  const details = window.cmaFinalChapterDetails;
  const chapters = window.cmaFinalChapters || {};
  Object.keys(details).forEach((slug) => {
    const titles = chapters[slug];
    const entries = Object.entries(details[slug]);
    if (!Array.isArray(titles) || titles.length !== entries.length) return;
    details[slug] = Object.fromEntries(entries.map(([, value], index) => [titles[index], value]));
  });
})();
